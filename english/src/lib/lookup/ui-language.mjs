export function translateUi(text, locale = 'vi') {
  if (typeof text !== 'string' || !text || locale === 'vi') {
    return text;
  }
  const entry = UI_TRANSLATIONS[text];
  if (!entry) {
    return text;
  }
  return entry[locale] ?? text;
}
