export function translateMyWords(text, locale) {
  if (typeof text !== 'string') return text;
  if (!locale || locale === 'vi') return text;
  const entry = MYWORDS_UI_TRANSLATIONS[text];
  if (!entry) return text;
  return entry[locale] !== undefined ? entry[locale] : text;
}
