export function translateSpotify(text, locale) {
  if (typeof text !== 'string') return text;
  if (!locale || locale === 'vi') return text;
  const entry = SPOTIFY_UI_TRANSLATIONS[text];
  if (!entry) return text;
  return entry[locale] || text;
}
